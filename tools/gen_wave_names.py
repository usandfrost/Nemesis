#!/usr/bin/env python3
"""Generates firmware/src/app/WaveNames.inc from the wavetable catalogue (content/data/wavetables/catalogue.json): for each of the 200 factory
banks its display name (upper case, as the WAVE knob shows it) and the basic wave it is nearest to (0 SIN, 1 TRI, 2 SAW, 3 SQR), which is what an
oscillator plays when the bank's file is not on the card. Usage: gen_wave_names.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
cat = json.load(open(f"{HERE}/../content/data/wavetables/catalogue.json"))
assert len(cat) == 200
near = {"SIN": 0, "TRI": 1, "SAW": 2, "SQR": 3}
out = ["// GENERATED by tools/gen_wave_names.py from the wavetable catalogue. Do not edit.",
       "// {name, nearest basic wave: 0 SIN 1 TRI 2 SAW 3 SQR, catalogue category: 0 basic 1 vocal 2 metallic 3 harmonic 4 chip 5 complex}"]
for b in cat:
    best = b["probe"][0]["best"] if b.get("probe") else "SAW"
    out.append('{"%s", %d, %d},' % (b["label"].upper(), near.get(best, 2), b["category"]))
open(f"{HERE}/../firmware/src/app/WaveNames.inc", "w").write("\n".join(out) + "\n")
print("wrote", len(cat), "names")
