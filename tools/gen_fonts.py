#!/usr/bin/env python3
"""Converts the panel's two fonts (Chakra Petch, IBM Plex Mono; both SIL OFL, tools/fonts/) into anti-aliased 4-bit bitmaps for the
firmware's screen, at the sizes and weights the mockup's CSS uses. Writes firmware/src/gfx/fonts/Fonts.{h,cpp}.

Each glyph is cropped to its ink; the advance is kept in 1/16 pixel so letter spacing and proportional text land where the browser puts
them. Symbols the fonts lack (the play triangle, the stop square, the small triangle, the ring and dot of the CLEAR and ADD keys) are drawn here as shapes.

  python3 tools/gen_fonts.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "tools", "fonts")
OUT = os.path.join(ROOT, "firmware", "src", "gfx", "fonts")

# (C name, file, px size) -- the CSS's font declarations on the screen
SPECS = [
    ("kDisplay600_16", "ChakraPetch-SemiBold.ttf", 16),
    ("kDisplay600_18", "ChakraPetch-SemiBold.ttf", 18),
    ("kDisplay600_20", "ChakraPetch-SemiBold.ttf", 20),
    ("kDisplay700_16", "ChakraPetch-Bold.ttf", 16),
    ("kDisplay700_20", "ChakraPetch-Bold.ttf", 20),
    ("kDisplay700_22", "ChakraPetch-Bold.ttf", 22),
    ("kMono400_16", "IBMPlexMono-Regular.ttf", 16),
    ("kMono400_17", "IBMPlexMono-Regular.ttf", 17),
    ("kMono400_20", "IBMPlexMono-Regular.ttf", 20),
    ("kMono400_22", "IBMPlexMono-Regular.ttf", 22),
    ("kMono500_25", "IBMPlexMono-Medium.ttf", 25),
    ("kMono600_16", "IBMPlexMono-SemiBold.ttf", 16),
    ("kMono600_17", "IBMPlexMono-SemiBold.ttf", 17),
    ("kMono600_20", "IBMPlexMono-SemiBold.ttf", 20),
    ("kMono600_22", "IBMPlexMono-SemiBold.ttf", 22),
]

# ASCII plus what the screen's text uses: middle dot, plus-minus, en dash, minus, right arrow, and drawn symbols: the triangles, the square, and the ADD and CLEAR keys as they are printed
EXTRA = [0xB7, 0xB1, 0x2013, 0x2212, 0x2192, 0x2026, 0x25B6, 0x25B8, 0x25A0, 0x25CF, 0x25CB]
DRAWN = {0x25B6, 0x25B8, 0x25A0, 0x25CF, 0x25CB}
CODEPOINTS = list(range(32, 127)) + EXTRA


def drawn_glyph(cp, size, ascent):
    """A shape for a symbol the font lacks, sized to the cap height. Returns (alpha image, dx, dy_top, advance)."""
    cap = round(size * 0.68)
    scale = 4
    if cp == 0x25B8:      # small right triangle
        h = round(cap * 0.62)
    else:
        h = cap
    w = round(h * 0.9) if cp not in (0x25A0, 0x25CF, 0x25CB) else h
    big = Image.new("L", (w * scale, h * scale), 0)
    d = ImageDraw.Draw(big)
    if cp == 0x25A0:
        d.rectangle([0, 0, w * scale - 1, h * scale - 1], fill=255)
    elif cp == 0x25CF:
        d.ellipse([0, 0, w * scale - 1, h * scale - 1], fill=255)
    elif cp == 0x25CB:
        d.ellipse([0, 0, w * scale - 1, h * scale - 1], outline=255, width=max(scale, round(size * scale * 0.09)))
    else:
        d.polygon([(0, 0), (w * scale - 1, h * scale / 2), (0, h * scale - 1)], fill=255)
    img = big.resize((w, h), Image.LANCZOS)
    top = ascent - round(size * 0.70) + (cap - h) // 2   # centred on the cap height
    return img, 1, top, (w + 3) * 16


def build(name, file, size):
    font = ImageFont.truetype(os.path.join(FONTS, file), size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for cp in CODEPOINTS:
        ch = chr(cp)
        if cp in DRAWN:
            img, dx, top, adv16 = drawn_glyph(cp, size, ascent)
        else:
            adv16 = round(font.getlength(ch) * 16)
            box = font.getbbox(ch, anchor="ls")          # relative to the left of the baseline
            if box[2] <= box[0] or box[3] <= box[1]:
                glyphs.append((cp, len(bits), 0, 0, 0, 0, adv16))
                continue
            img = Image.new("L", (box[2] - box[0], box[3] - box[1]), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
            dx, top = box[0], ascent + box[1]                # top: rows below the line's top (ascent above the baseline)
        w, h = img.size
        px = img.load()
        off = len(bits)
        nib = []
        for y in range(h):
            for x in range(w):
                # a gamma below 1 thickens the edges the way the browser's font smoothing on macOS does (the mockup was judged there)
                nib.append(round(15 * (px[x, y] / 255) ** 0.72))
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            bits.append(nib[i] | (nib[i + 1] << 4))
        glyphs.append((cp, off, w, h, dx, top, adv16))
    return ascent, descent, glyphs, bits


def main():
    os.makedirs(OUT, exist_ok=True)
    h = ["// GENERATED by tools/gen_fonts.py from tools/fonts (Chakra Petch, IBM Plex Mono: SIL Open Font License 1.1). Do not edit.",
         "#pragma once", "", '#include "gfx/Font.h"', "", "namespace gfx::fonts {", ""]
    c = ["// GENERATED by tools/gen_fonts.py from tools/fonts (Chakra Petch, IBM Plex Mono: SIL Open Font License 1.1). Do not edit.",
         '#include "gfx/fonts/Fonts.h"', "", "namespace gfx::fonts {", ""]
    total = 0
    for name, file, size in SPECS:
        ascent, descent, glyphs, bits = build(name, file, size)
        total += len(bits) + len(glyphs) * 16   # sizeof(gfx::Glyph)
        h.append(f"extern const Font {name};   // {file} {size} px")
        c.append(f"static const uint8_t {name}_bits[{max(1, len(bits))}] = {{")
        for i in range(0, len(bits), 32):
            c.append("    " + ",".join(str(b) for b in bits[i:i + 32]) + ",")
        if not bits:
            c.append("    0,")
        c.append("};")
        c.append(f"static const Glyph {name}_glyphs[{len(glyphs)}] = {{")
        for g in glyphs:
            c.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
        c.append("};")
        c.append(f"const Font {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bits, {ascent}, {descent}, {size}}};")
        c.append("")
    h += ["", "}  // namespace gfx::fonts", ""]
    c += ["}  // namespace gfx::fonts", ""]
    open(os.path.join(OUT, "Fonts.h"), "w").write("\n".join(h))
    open(os.path.join(OUT, "Fonts.cpp"), "w").write("\n".join(c))
    print(f"{len(SPECS)} fonts, {total / 1024:.0f} KB of flash")


if __name__ == "__main__":
    main()
