        [[nodiscard]] StereoSample processSample() noexcept
        {
            applyCutRequest(); // [b39 E-tails] one acquire load while nothing is requested
            applyEngineRequests(); // [T-CGUI-81] one acquire load while nothing is requested
            if (cutLeft_ > 0)
                --cutLeft_; // [b39 E-tails] a reshape waits out the cut fade, so its hard reset lands on silence
            else if (cutInFlight_)
                landCut(); // [b39 review 2] the reshape and the held-back notes, on silence
            else
                applyPoolRequest(); // [T-CGUI-79 A4] one acquire load while nothing is requested
            ++sampleClock_; // release timestamps for the unison-grace window (bookkeeping, no output effect)
            tickDrifters();
            if (phaseSlewLeft_ > 0)
                stepPhaseSlew (1); // [T-CGUI-79 A4] a modulated phase spread's glide (row 338)
            StereoSample out = isMonophonic() ? processMono() : processPoly();
            if (cutLeft_ > 0) // [b35 review 8] the cut's declick: the outgoing output, mirrored, ramped to 0
            {
                // [b35 review 9] `cutLeft_` was already decremented this sample: gain N/N (the newest sample, repeated)
                // down to 2/N; the sample `cutLeft_` reaches 0 on is the ramp's 0.
                const float g = static_cast<float> (cutLeft_ + 1) * cutStep_;
                const StereoSample& t = cutTail_[static_cast<std::size_t> (cutSamples_ - 1 - cutLeft_)];
                out.left += g * t.left;
                out.right += g * t.right;
            }
            outRing_[static_cast<std::size_t> (outRingPos_)] = out; // [b35 review 8]
            outRingPos_ = outRingPos_ + 1 == cutSamples_ ? 0 : outRingPos_ + 1;
            // [T-CGUI-46 leaf 2] One epoch compare while nothing engine-wide is routed (bit-exact).
            if (engineBoundCount_ > 0 && (engineLiveCount_ > 0 || engineDirty_ || voices_[0].liveEpoch() != engineEpoch_))
                applyEngineDests (false);
            return out;
        }

