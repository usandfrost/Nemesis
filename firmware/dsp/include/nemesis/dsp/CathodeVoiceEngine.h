        [[nodiscard]] OrganicVoiceMults organicMultsFor (std::uint32_t noteOrdinal, int voice) const noexcept
        {
            OrganicVoiceMults m;
            if (!organicOn_.load (std::memory_order_relaxed))
                return m;
            const float amount01 = organicAmount01_.load (std::memory_order_relaxed);
            // A COST early-out, NOT a correctness guard, and the T-CMP-11 battery is what
            // established the difference: mutating `<= 0.0f` to `< 0.0f` survives, and it must —
            // at amount 0 every deviation is `draw * max * 0`, so all three mults come out
            // exactly 1.0 whether this line fires or not. It is kept because skipping four
            // transcendentals per voice-trigger is worth a branch, and it is LABELLED because a
            // guard no mutation can kill otherwise reads as protection it does not provide
            // (the T-CORE-02 dead-guard rule). Classification (c): equivalent mutant, by design.
            if (amount01 <= 0.0f)
                return m;
            const std::uint32_t seed = organicSeed_.load (std::memory_order_relaxed);
            const auto v = static_cast<std::uint32_t> (voice);

            const float pitchCents = organicDrawBipolar (seed, noteOrdinal, v, kOrganicDimPitch)
                                     * kOrganicPitchCentsMax * amount01;
            m.pitch = static_cast<float> (fm::exp2 (static_cast<Real> (pitchCents) / 1200.0));

            const float ampDb = organicDrawBipolar (seed, noteOrdinal, v, kOrganicDimAmp)
                                * kOrganicAmpDbMax * amount01;
            m.amp = static_cast<float> (std::pow (10.0, static_cast<Real> (ampDb) / 20.0));

            const float cutoffOct = organicDrawBipolar (seed, noteOrdinal, v, kOrganicDimCutoff)
                                    * kOrganicCutoffOctavesMax * amount01;
            m.cutoff = static_cast<float> (fm::exp2 (static_cast<Real> (cutoffOct)));
            return m;
        }

